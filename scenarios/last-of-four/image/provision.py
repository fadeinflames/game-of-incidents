#!/usr/bin/env python3
"""dns-provision: renders the configuration of one replica of the internal DNS cluster from the template.

The replicas and their addresses come from the inventory. The result goes to a directory (unbound.conf inside it) or
to stdout. The rebuild job (dns-rebuild) calls this program with the options from /etc/dns-provision/rebuild.conf.
"""
import argparse
import os
import sys

VERSION = "2.4"
TEMPLATE = "/etc/dns-provision/unbound.conf.tmpl"
INVENTORY = "/etc/dns-provision/inventory"


def read_inventory(path):
    replicas = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.split("#", 1)[0].split()
            if len(fields) >= 2:
                replicas.append((fields[0], fields[1]))
    return replicas


def main():
    ap = argparse.ArgumentParser(
        prog="provision",
        description="Render the unbound.conf of one replica of the internal DNS cluster.",
    )
    ap.add_argument("--replica", required=True, help="replica name from the inventory, e.g. ns1")
    ap.add_argument("--os", default="bookworm", help="release the replica is built on (goes to the header of the file)")
    ap.add_argument(
        "--auto-forwarders",
        action="store_true",
        help="add a forward zone for '.' that points at another replica from the inventory (the next one in the list). "
        "Meant for sites where a replica has no route to the Internet and another replica does",
    )
    ap.add_argument("--template", default=TEMPLATE, help=f"template file (default {TEMPLATE})")
    ap.add_argument("--inventory", default=INVENTORY, help=f"inventory file (default {INVENTORY})")
    out = ap.add_mutually_exclusive_group(required=True)
    out.add_argument("--out", metavar="DIR", help="write DIR/unbound.conf")
    out.add_argument("--stdout", action="store_true", help="print the rendered file, write nothing")
    args = ap.parse_args()

    replicas = read_inventory(args.inventory)
    names = [n for n, _ in replicas]
    if args.replica not in names:
        sys.exit(f"dns-provision: replica {args.replica} is not in {args.inventory}")
    idx = names.index(args.replica)
    addr = replicas[idx][1]

    options = f"--os {args.os}" + (" --auto-forwarders" if args.auto_forwarders else "")
    forwarders = ""
    summary = "none"
    if args.auto_forwarders and len(replicas) > 1:
        fwd_name, fwd_addr = replicas[(idx + 1) % len(replicas)]
        forwarders = f'forward-zone:\n    name: "."\n    forward-addr: {fwd_addr}    # {fwd_name}\n'
        summary = f"{fwd_addr} ({fwd_name}), picked automatically"

    with open(args.template, encoding="utf-8") as f:
        body = f.read()
    body = body.replace("{{NAME}}", args.replica).replace("{{ADDR}}", addr).replace("{{FORWARDERS}}", forwarders)
    text = (
        f"# Generated by dns-provision {VERSION} for replica {args.replica}. Do not edit by hand: the next rebuild overwrites this file.\n"
        f"# Template: {args.template}   Options: {options}\n" + body
    )

    if args.stdout:
        sys.stdout.write(text)
        return
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "unbound.conf")
    with open(path + ".tmp", "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(path + ".tmp", path)
    print(f"dns-provision: {args.replica}: listen {addr}, forwarders: {summary} -> {path}")


if __name__ == "__main__":
    main()
