#!/bin/sh
# SECRET. The story: the platform team applies a small change to the capacity controller ("add pods earlier when the
# queue grows"). The plan file of that change was generated in February, in a branch that waited for its turn since
# then, and it carries the bounds of the dispatcher pool from that time: 2..4 pods. The service has grown fourfold
# since: it needs 8. The controller applies the plan as it is, the pool shrinks from 8 to 4 pods, the queue cannot be
# emptied any more and jobs start to miss their 20 s start deadline.
set -u
t_end=$(( $(date +%s) + 215 ))
left() { [ "$(date +%s)" -lt "$t_end" ]; }
fail() { echo "break: FAILED, $*" >&2; exit 1; }
qstats() { kubectl -n runs exec deploy/queue -- python3 /app/app.py stats </dev/null 2>/dev/null; }
cstatus() { kubectl -n platform exec deploy/capacity-controller -- python3 /app/app.py stats </dev/null 2>/dev/null; }
num() { v=$(printf '%s' "$1" | jq -r "$2 // $3" 2>/dev/null); printf '%s' "${v:-$3}"; }

for d in runs/queue runs/submitter runs/dispatcher platform/capacity-controller; do
  kubectl -n "${d%/*}" rollout status "deploy/${d#*/}" --timeout=100s >/dev/null 2>&1 || fail "deployment $d is not ready"
done

# the world before the change: revision 41 is in force, 8 dispatchers, jobs start at once
healthy=0; rev=0; live=0; started=0; waiting=-1
while left; do
  c=$(cstatus); q=$(qstats)
  rev=$(num "$c" '.plan_in_force.revision' 0); live=$(num "$c" '.pools.dispatcher.live' 0)
  started=$(num "$q" '.totals.started' 0); waiting=$(num "$q" '.waiting' -1)
  seen=$(num "$q" '.dispatchers_seen_10s' 0)
  if [ "$rev" = "41" ] && [ "$live" = "8" ] && [ "$seen" -ge 8 ] && [ "$started" -ge 30 ] && [ "$waiting" -ge 0 ] && [ "$waiting" -le 12 ]; then healthy=1; break; fi
  sleep 2
done
[ "$healthy" = "1" ] || fail "the stand did not become healthy (revision $rev, dispatchers $live, started $started, waiting $waiting)"

# the change
plan=$(cat <<'EOF'
# Capacity plan for capacity-controller. Generated by plan-gen from the sizing sheet.
# The controller applies this object as it is and keeps every applied revision in capacity-plan-history.
[plan]
generated_at = 2026-02-03T09:14:11Z
sizing_input = sizing sheet snapshot 2026-02-01: dispatcher peak 1.4 jobs/s, 1 job/s per pod, headroom 25 %
change       = CAP-733: add pods earlier when the queue grows (backlog_per_pod 20 -> 15)

[pool dispatcher]
min_replicas    = 2
max_replicas    = 4
backlog_per_pod = 15
EOF
)
kubectl -n platform patch configmap capacity-plan --type=merge \
  -p "$(jq -n --arg p "$plan
" '{data: {"plan.conf": $p}}')" >/dev/null || fail "cannot apply the new capacity plan"

# wait until the failure is there: the controller enforces the new plan, the pool is down to its cap,
# the queue is long and the first jobs have missed the start deadline
rev=0; reps=0; failed=0; waiting=0
while left; do
  c=$(cstatus); q=$(qstats)
  rev=$(num "$c" '.plan_in_force.revision' 0)
  reps=$(kubectl -n runs get deploy dispatcher -o jsonpath='{.spec.replicas}' 2>/dev/null); reps=${reps:-0}
  failed=$(num "$q" '.totals.failed_to_start' 0); waiting=$(num "$q" '.waiting' 0)
  if [ "$rev" = "42" ] && [ "$reps" -ge 2 ] && [ "$reps" -le 4 ] && [ "$failed" -ge 6 ] && [ "$waiting" -ge 80 ]; then
    echo "break: done (plan revision $rev, $reps dispatchers, $waiting jobs waiting, $failed failed to start)"
    exit 0
  fi
  sleep 3
done
fail "the failure did not develop (plan revision $rev, dispatchers $reps, waiting $waiting, failed to start $failed)"
