#!/usr/bin/env node
// Licence report of the npm dependencies, generated from package-lock.json (and node_modules when it exists, for the
// packages whose lockfile entry has no `license` field). Repeatable: `node scripts/license-report.mjs > docs/legal/third-party-licenses.md`
// or `--check` to fail (exit 1) when a package has an unknown licence or one that is not on the allow list.
// Nothing is downloaded and no dependency code runs.
import { readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = process.env.LICENSE_REPORT_ROOT || join(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));

// permissive or weak-copyleft licences that are fine to depend on from Apache-2.0 code (used as unmodified libraries)
const PERMISSIVE = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|Unlicense|CC0-1\.0|BlueOak-1\.0\.0|Python-2\.0|CC-BY-4\.0)$/;
const WEAK_COPYLEFT = /^(MPL-2\.0|LGPL-[0-9.]+(-only|-or-later)?)$/;

// Old packages declare the licence in a `licenses` array, which the lockfile does not copy. Checked in their package.json
// and LICENSE files (2026-10-11): all three are MIT, copyright Brian White.
const KNOWN = { ssh2: "MIT", buildcheck: "MIT", "cpu-features": "MIT" };

function licenseOf(path, entry) {
  const known = KNOWN[path.replace(/^.*node_modules\//, "")];
  if (known && !entry.license) return known;
  if (entry.license) return typeof entry.license === "string" ? entry.license : JSON.stringify(entry.license);
  const manifest = join(root, path, "package.json");
  if (existsSync(manifest)) {
    try {
      const m = JSON.parse(readFileSync(manifest, "utf8"));
      if (m.license) return typeof m.license === "string" ? m.license : m.license.type || JSON.stringify(m.license);
    } catch { /* fall through */ }
  }
  return "UNKNOWN";
}

const rows = [];
for (const [path, entry] of Object.entries(lock.packages)) {
  if (!path || entry.link) continue;
  if (!path.includes("node_modules/")) continue; // the workspaces themselves
  const name = path.replace(/^.*node_modules\//, "");
  rows.push({ name, version: entry.version, license: licenseOf(path, entry), dev: Boolean(entry.dev), optional: Boolean(entry.optional) });
}

const parts = (l) => l.replace(/[()]/g, "").split(/\s+(?:AND|OR)\s+/);
const classify = (l) => {
  if (l === "UNKNOWN") return "unknown";
  const ps = parts(l);
  if (ps.every((p) => PERMISSIVE.test(p))) return "permissive";
  if (ps.every((p) => PERMISSIVE.test(p) || WEAK_COPYLEFT.test(p))) return "weak-copyleft";
  return "review";
};

const byLicense = new Map();
for (const r of rows) {
  if (!byLicense.has(r.license)) byLicense.set(r.license, []);
  byLicense.get(r.license).push(r);
}
const attention = rows.filter((r) => classify(r.license) !== "permissive");

if (process.argv.includes("--check")) {
  const bad = attention.filter((r) => classify(r.license) !== "weak-copyleft");
  for (const r of bad) console.error(`licence needs a decision: ${r.name}@${r.version}: ${r.license}`);
  process.exit(bad.length ? 1 : 0);
}

const out = [];
out.push("# Лицензии зависимостей npm / npm dependency licences", "");
out.push("Файл создаётся скриптом `node scripts/license-report.mjs` из `package-lock.json`; не правь его вручную. / Generated by `node scripts/license-report.mjs` from `package-lock.json`; do not edit by hand.", "");
out.push(`Пакетов / packages: ${rows.length} (из них только для разработки / dev only: ${rows.filter((r) => r.dev).length}, необязательных / optional: ${rows.filter((r) => r.optional).length}).`, "");
out.push("## Сводка / Summary", "", "| Лицензия / Licence | Пакетов / Packages | Класс / Class |", "|---|---:|---|");
for (const [l, list] of [...byLicense.entries()].sort((a, b) => b[1].length - a[1].length)) out.push(`| ${l} | ${list.length} | ${classify(l)} |`);
out.push("", "## Требуют внимания / Needs attention", "");
if (!attention.length) out.push("Нет / None.");
else {
  out.push("| Пакет / Package | Лицензия / Licence | Прод / Prod | Необязательный / Optional | Класс / Class |", "|---|---|---|---|---|");
  for (const r of attention.sort((a, b) => a.name.localeCompare(b.name))) out.push(`| ${r.name}@${r.version} | ${r.license} | ${r.dev ? "нет / no" : "да / yes"} | ${r.optional ? "да / yes" : "нет / no"} | ${classify(r.license)} |`);
}
out.push("", "## Как читать / How to read", "",
  "- **permissive**: MIT, ISC, BSD, Apache-2.0 и подобные; ограничений на Apache-2.0 код нет, нужна только атрибуция (тексты лежат в самих пакетах). / no restrictions on Apache-2.0 code beyond attribution.",
  "- **weak-copyleft**: MPL-2.0 (файловый копилефт) и LGPL (библиотеки, подключаемые динамически как отдельные бинарные файлы). Используются без изменений; замена библиотеки пользователем не затруднена. / used unmodified as separate libraries.",
  "- **unknown / review**: нужно ручное решение до публикации. / needs a manual decision before release.", "");
process.stdout.write(out.join("\n") + "\n");
